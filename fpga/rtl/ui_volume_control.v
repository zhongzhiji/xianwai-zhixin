// Hold S1+S2 together to focus master volume. Chord release is consumed,
// including staggered releases; all single-key actions keep their contract.
module ui_volume_control #(
    parameter HOLD_CYCLES=21000000,DEFAULT_VOLUME_STEP=12
)(
    input wire clk,reset_n,
    input wire [2:0] pressed,short_action,long_action,
    output wire [2:0] normal_short,normal_long,
    output reg volume_edit,
    output reg [4:0] volume_step,
    output reg [1:0] practice_mode,
    output reg backing_enabled,
    // 三键齐按（pressed 高有效，3'b111 = S1+S2+S3，此前唯一空闲的组合）：
    //   短按 = fx_step 脉冲（顶层循环 旁路→回声→合唱→混响）
    //   长按 = test_step 脉冲（顶层循环 关→4→8→16→32 音测试）
    // 赛题"评分规则3 现场验证"要求能当场切 N 音测试、当场做效果器旁路对比，
    // 原来这两个都是编译期 parameter，评委要看只能重新编译，所以改成运行时。
    output reg fx_step,
    output reg test_step
);
    reg chord_lock,chord_fired,exit_lock;
    reg [24:0] chord_count;
    reg [2:0] chord_kind;
    wire [2:0] pair_kind=pressed==3'b011 ? 3'd1 :
        !volume_edit && pressed==3'b101 ? 3'd2 :
        !volume_edit && pressed==3'b110 ? 3'd3 :
        !volume_edit && pressed==3'b111 ? 3'd4 : 3'd0;
    wire chord=(pair_kind!=0);
    // 3'b111 现在是正常的第四种组合，由 chord 吞掉，不再单独吞
    wire consume=chord || chord_lock || exit_lock || volume_edit;
    assign normal_short=consume ? 3'd0 : short_action;
    assign normal_long=consume ? 3'd0 : long_action;
    always @(posedge clk or negedge reset_n) begin
        if(!reset_n)begin
            chord_lock<=0;chord_fired<=0;chord_count<=0;exit_lock<=0;
            chord_kind<=0;practice_mode<=0;backing_enabled<=0;
            volume_edit<=0;volume_step<=DEFAULT_VOLUME_STEP;
            fx_step<=0;test_step<=0;
        end else begin
            fx_step<=0;test_step<=0;
            if(chord && (!chord_lock || chord_kind==pair_kind))begin
                chord_lock<=1;chord_kind<=pair_kind;
                if(!chord_fired)begin
                    if(chord_count>=HOLD_CYCLES-1)begin
                        chord_fired<=1;
                        case(pair_kind)
                            1:begin volume_edit<=~volume_edit;if(volume_edit)exit_lock<=1;end
                            2:practice_mode<=practice_mode==2 ? 0 : practice_mode+1'b1;
                            3:backing_enabled<=~backing_enabled;
                            4:test_step<=1'b1;
                        endcase
                    end else chord_count<=chord_count+1'b1;
                end
            end else chord_count<=0;
            // Keep one extra clock after release, covering release pulses
            // generated by the debouncers on the same edge.
            // 三键齐按的"短按"在松开这一刻才兑现：没撑到 HOLD_CYCLES 就松手
            // = 短按 → fx_step；撑到了 → 上面已经发过 test_step，chord_fired=1，
            // 这里就不会再补一刀 fx_step。
            if(chord_lock && pressed==0 && short_action==0 && long_action==0)begin
                if(chord_kind==3'd4 && !chord_fired)fx_step<=1'b1;
                chord_lock<=0;chord_fired<=0;chord_kind<=0;
            end
            // Keys already held when S3 exits belong to volume editing.
            // Consume their eventual long/release pulses before normal
            // playback/preset/page commands can be accepted again.
            if(exit_lock && pressed==0 && short_action==0 && long_action==0)exit_lock<=0;
            if(volume_edit && !chord && !chord_lock)begin
                if(short_action[2] || long_action[2])begin volume_edit<=0;exit_lock<=1;end
                else if(short_action[0] || long_action[0])begin
                    if(volume_step!=0)volume_step<=volume_step-1'b1;
                end else if(short_action[1] || long_action[1])begin
                    if(volume_step<20)volume_step<=volume_step+1'b1;
                end
            end
        end
    end
endmodule
